#!/usr/bin/env python3
"""Generates frontend/src/lib/permissions.ts from the authoritative C# catalogue (Permissions.cs).

Run after changing backend/src/Scholar.Domain/Access/Permissions.cs:  python3 scripts/gen-permissions.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / "backend/src/Scholar.Domain/Access/Permissions.cs").read_text()
body = source[source.index("public static class Permissions"):source.index("public sealed record PermissionDefinition")]

groups: dict[str, list[tuple[str, str]]] = {}
current = None
for line in body.splitlines():
    if m := re.match(r"\s{4}public static class (\w+)", line):
        current = m.group(1)
        groups[current] = []
    elif current and (m := re.match(r'\s+public const string (\w+) = "([^"]+)";', line)):
        groups[current].append((m.group(1), m.group(2)))

out = ["// Generated by scripts/gen-permissions.py from Permissions.cs — do not edit by hand.", "", "export const P = {"]
for group, items in groups.items():
    out.append(f"  {group}: {{")
    out.extend(f'    {name}: "{key}",' for name, key in items)
    out.append("  },")
out += ["} as const;", "", "type Values<T> = T[keyof T];", "export type Permission = Values<{ [G in keyof typeof P]: Values<(typeof P)[G]> }>;", ""]
(root / "frontend/src/lib/permissions.ts").write_text("\n".join(out))
print(f"wrote {sum(len(v) for v in groups.values())} permissions in {len(groups)} groups")
